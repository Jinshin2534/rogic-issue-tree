import Foundation
import IssueTreeCore

struct GuidePage: Identifiable {
    let id: String
    let title: String
    let symbol: String
    let lead: String
    let blocks: [GuideBlock]
}

enum GuideBlock {
    case heading(String)
    case paragraph(String)
    case bullets([String])
    /// 用語と説明の組
    case terms([(String, String)])
    case tip(String)
    case checklist([String])
    /// 例のツリー（Markdown 形式。見出し = トップイシュー）
    case example(title: String, kind: TreeKind, markdown: String)
}

enum Guide {
    static let pages: [GuidePage] = [basics, types, why, how, what, mece, cuts, goodIssue, depth, checklist]

    static func page(_ id: String) -> GuidePage? { pages.first { $0.id == id } }

