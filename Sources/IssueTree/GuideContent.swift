import Foundation

struct GuidePage: Identifiable {
    let id: String
    let title: String
    let symbol: String
    let lead: String
    let blocks: [GuideBlock]
}

enum GuideBlock {
    case heading(String)
    case paragraph(String)
    case bullets([String])
    /// 用語と説明の組
    case terms([(String, String)])
    case tip(String)
    case checklist([String])
    /// 例のツリー（Markdown 形式。見出し = トップイシュー）
    case example(title: String, markdown: String)
}

enum Guide {
    static let pages: [GuidePage] = [basics, types, mece, cuts, goodIssue, depth, checklist]

    static func page(_ id: String) -> GuidePage? { pages.first { $0.id == id } }

    static let basics = GuidePage(
        id: "basics", title: "イシューツリーの基本", symbol: "point.3.connected.trianglepath.dotted",
        lead: "大きな問いを、答えられる大きさの問いに分けていく道具です。左に行くほど抽象的、右に行くほど具体的になります。",
        blocks: [
            .heading("作る流れ"),
            .bullets([
                "① トップイシューを1文で書く。「〜なのはなぜか」「どうすれば〜できるか」など、問いの形にする",
                "② 1層目を、モレなくダブりなく（MECE）分ける。ここが一番大事で、切り口の選び方で良し悪しが決まる",
                "③ 2層目以降は、打ち手や調べ方が浮かぶ具体さになるまで分ける",
                "④ 重要そうな箇所に印（赤字）をつけ、そこに時間を使う",
                "⑤ 深い論点は「深掘り」で別のツリーに切り出し、そこをトップにしてもう一度分ける",
            ]),
            .heading("左右の関係"),
            .terms([
                ("左 → 右（Why So?）", "「それはなぜ？」「具体的には？」と問うと、右の要素が出てくる"),
                ("右 → 左（So What?）", "「つまり何が言える？」と問うと、左の要素にまとまる"),
            ]),
            .tip("左右どちらの向きに読んでも話がつながっていれば、よいツリーです。"),
            .example(title: "例：原因を分解する", markdown: """
            # 若手の育成が上手く進まない
            - 育成の仕組みが整っていないから
              - 体系的なカリキュラムが無いから
              - フィードバックを受ける場が無いから
            - 指導する側のスキル・意識が足りないから
              - 育成を上司の役割と認識していないから
              - 上司に育成の時間が無いから
            - 若手本人の成長意欲を引き出せていないから
            """),
        ]
    )

    static let types = GuidePage(
        id: "types", title: "3種類のツリー", symbol: "square.stack.3d.up",
        lead: "問いの種類によって、ツリーの形が変わります。最初に「何を知りたいのか」を決めてから作り始めます。",
        blocks: [
            .terms([
                ("Why ツリー（原因）", "「なぜ起きているのか」を分ける。問題の真因を見つけるために使う"),
                ("How ツリー（打ち手）", "「どうすれば解決できるか」を分ける。取れる手段を広く出し、選ぶために使う"),
                ("What ツリー（要素）", "「何でできているか」を分ける。売上や費用など、全体の構成をつかむために使う"),
            ]),
            .tip("順番は「What で全体をつかむ → Why で原因を絞る → How で打ち手を出す」が基本です。Why の末端を深掘りして How ツリーにつなげると、原因と打ち手が対応した形になります。"),
            .example(title: "What ツリー：売上の構成", markdown: """
            # 店舗の売上
            - 客数
              - 新規客数
              - リピート客数
            - 客単価
              - 1品あたりの単価
              - 1回あたりの購入点数
            """),
            .example(title: "How ツリー：打ち手を出す", markdown: """
            # どうすればリピート客を増やせるか
            - 初回の体験を良くする
              - 接客の質をそろえる
              - 待ち時間を減らす
            - もう一度来る理由をつくる
              - 次回使える特典を渡す
              - 新商品の案内を送る
            - 離れた客を呼び戻す
              - 来なくなった理由を聞く
            """),
        ]
    )

    static let mece = GuidePage(
        id: "mece", title: "MECE（モレなくダブりなく）", symbol: "square.grid.2x2",
        lead: "同じ親の下に並ぶ要素は、重ならず（ダブりなく）、足すと親の全体になる（モレなく）ように分けます。",
        blocks: [
            .heading("よくある失敗"),
            .terms([
                ("ダブり", "「若手」と「新卒」を並べる。新卒は若手の一部なので重なっている"),
                ("モレ", "顧客を「法人」「個人」に分けたのに、行政や団体が抜けている"),
                ("粒度のズレ", "「営業部」と「田中さん」を並べる。同じ階層に大きさの違うものが混ざっている"),
                ("軸の混在", "「東日本」「西日本」「若年層」を並べる。地域と年代という別の軸が混ざっている"),
            ]),
            .heading("MECE にするコツ"),
            .bullets([
                "1つの親の下では、分ける軸を1つに決める（地域なら地域だけで分ける）",
                "「A と A 以外」で分けると、必ずモレなくダブりなくなる（例：既存顧客／新規顧客）",
                "数式に直せるものは数式で分ける（売上 = 客数 × 客単価）。数式が成り立てば MECE になる",
                "どうしても分けきれないときは「その他」を置き、中身が大きくないかを確かめる",
            ]),
            .tip("完璧な MECE にこだわりすぎないこと。大事なのは、答えに効く大きな要素がモレていないことです。"),
        ]
    )

    static let cuts = GuidePage(
        id: "cuts", title: "切り口のパターン", symbol: "scissors",
        lead: "1層目の切り口に迷ったら、ここから当てはまるものを選びます。複数試して、答えが出しやすいものを採用します。",
        blocks: [
            .terms([
                ("数式で分ける", "売上 = 客数 × 客単価、利益 = 売上 − 費用。抜けが出にくく、数字で確かめられる"),
                ("流れ（プロセス）で分ける", "認知 → 興味 → 購入 → 継続。どの段階で詰まっているかを探すときに使う"),
                ("時間で分ける", "過去／現在／未来、短期／中期／長期"),
                ("関わる人で分ける", "顧客・自社・競合（3C）、経営層・現場・取引先など"),
                ("内と外で分ける", "自社の中の要因／外部環境の要因。変えられることと変えられないことが分かれる"),
                ("対立する2つで分ける", "量と質、ハードとソフト、定量と定性、仕組みと人"),
                ("打ち手の型で分ける", "製品・価格・売り場・宣伝（4P）、増やす／減らす／やめる／始める"),
            ]),
            .tip("よい切り口は「分けた結果、差が見える」切り口です。どの要素も同じくらいに見えるなら、別の切り口を試します。"),
            .example(title: "流れで分ける例", markdown: """
            # 問い合わせが契約につながらないのはなぜか
            - 問い合わせの質が低い
              - 対象外の企業からの問い合わせが多い
            - 初回の商談で魅力が伝わっていない
              - 資料が相手の課題に合っていない
            - 見積もり後に止まっている
              - 価格が予算に合わない
              - 決裁者に会えていない
            """),
        ]
    )

    static let goodIssue = GuidePage(
        id: "issue", title: "よいイシューの立て方", symbol: "questionmark.bubble",
        lead: "ツリーの質は、トップイシュー（最初の問い）でほぼ決まります。分ける前に、問い自体を見直します。",
        blocks: [
            .heading("よいイシューの条件"),
            .bullets([
                "答えによって、次にやることが変わる（どちらの答えでも同じ行動なら、問う意味は薄い）",
                "今ある情報や調査で、答えを出せる",
                "範囲がはっきりしている（誰の・どこの・いつまでの話か）",
                "自分なりの仮説がある（「たぶん〜ではないか」と言える）",
            ]),
            .heading("問いを具体的にする"),
            .terms([
                ("ぼんやりした問い", "「売上を上げるには？」"),
                ("具体的な問い", "「来年度、既存顧客からの売上を1割伸ばすには、何を優先すべきか？」"),
            ]),
            .tip("主語・対象・期間・目標の数字を入れると、問いは一気に答えやすくなります。"),
        ]
    )

    static let depth = GuidePage(
        id: "depth", title: "どこまで分けるか・深掘り", symbol: "arrow.down.right.circle",
        lead: "末端が「次に何をするか」まで具体になったら止めます。深く分けること自体は目的ではありません。",
        blocks: [
            .heading("止める目安"),
            .bullets([
                "打ち手が浮かぶ、または調べ方（誰に聞くか・どのデータを見るか）が決まる",
                "「なぜ？」を重ねても、同じ答えや当たり前の答えしか出なくなった",
                "自分たちでは変えられない要因に行き着いた（天候、法律など）",
            ]),
            .heading("深掘り機能の使いどころ"),
            .bullets([
                "末端のうち、重要で、まだ分け足りないものを選んで ⌘↓（深掘り）",
                "そのノードをトップイシューにした新しいツリーが開くので、1層目からもう一度 MECE に分ける",
                "元のツリーは大きな地図、深掘りしたツリーは部分の詳しい地図として使い分ける",
                "⌘↑ で元のツリーに戻る。サイドバーで、深掘りの親子関係を一覧できる",
            ]),
            .tip("Why ツリーの真因を深掘りして「どうすれば〜を解消できるか」と問い直すと、そのまま How ツリーになります。"),
        ]
    )

    static let checklist = GuidePage(
        id: "check", title: "見直しチェックリスト", symbol: "checklist",
        lead: "ツリーができたら、人に見せる前に次の点を確かめます。",
        blocks: [
            .checklist([
                "トップイシューは問いの形で、範囲と目標がはっきりしているか",
                "同じ親の下の要素は、1つの軸で分けられているか",
                "同じ階層の要素の大きさ（粒度）はそろっているか",
                "大きな要素がモレていないか。「その他」が大きすぎないか",
                "左から右へ「なぜ？」、右から左へ「つまり？」で話がつながるか",
                "末端は、打ち手か調べ方が決まる具体さになっているか",
                "重要な箇所に印（赤字）をつけ、どこから手をつけるか決めたか",
            ]),
        ]
    )
}
